// Writes data.js from public fixtures, so the prototype opens without a build: `node prototypes/guided-reading/build-data.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';

const FIXTURES = { importer: 'src/fixtures/disassemblies/importer-signals.json', mill: 'src/fixtures/disassemblies/mill-harm.json' };
const root = new URL('../../', import.meta.url);
const data = Object.fromEntries(Object.entries(FIXTURES).map(([key, path]) => [key, JSON.parse(readFileSync(new URL(path, root), 'utf8'))]));
writeFileSync(new URL('data.js', import.meta.url),
  `// Generated by build-data.mjs from ${Object.values(FIXTURES).join(' and ')} (public fixtures). Do not edit.\nwindow.DISASSEMBLIES = ${JSON.stringify(data)};\n`);
