/** What the host returns after the three phases: here Mill's disassembly, relabelled as generated by the request's models. */
async function generated(request: GenerationRequest): Promise<Disassembly> {
  const d = mill();
  const { structure, content } = request.setup;
  d.id = 'g-new'; d.kind = 'generated';
  d.generation = { provider: structure.provider === 'local' ? 'local' : 'chatgpt', ...(structure.provider === 'local' ? { runtime: structure.runtime } : {}), model: structure.model === content.model ? structure.model : `${structure.model} + ${content.model}`, createdAt: '2026-10-26T10:00:00.000Z' };
  return validateDisassembly(d);
}

/** The desktop contract with a scripted account and provider; no tokens ever appear on this side. */
function desktop(options: { generate?: (request: GenerationRequest) => ReturnType<StudioBridge['generate']>; plan?: boolean; servers?: LocalServer[]; settings?: StudioSettings; draft?: () => DraftState; suggest?: (request: SuggestionRequest) => Promise<SuggestionResult> } = {}) {
  const saved = new Map<string, LearnerState>();
  const key = (k: ProgressKey) => `${'lessonId' in k ? k.lessonId : k.disassemblyId}:${k.revision}`;
  let status: AccountStatus = { state: 'signed-out', storage: true };
  let settings: StudioSettings = options.settings ?? defaultSettings;
  const listeners: ((progress: GenerationProgress) => void)[] = [];
  const arrivals: ((incoming: IncomingSource) => void)[] = [];
  const studio: StudioBridge = {
    pickSources: vi.fn(async () => ({ sources: [], errors: [{ name: 'a.pdf', message: '«a.pdf» non è supportato. Per ora puoi importare file .txt e .md.' }] })),
    accountStatus: async () => status,
    signIn: vi.fn(async () => { status = { state: 'signed-in', email: 'learner@example.com', planUsage: options.plan ?? true, storage: true }; return { ok: true as const, status }; }),
    cancelSignIn: async () => {},
    signOut: async () => (status = { state: 'signed-out', storage: true }),
    listModels: async () => ({ ok: true as const, models: [{ slug: 'model-a', name: 'Model A' }, { slug: 'model-b', name: 'Model B' }] }),
    generate: vi.fn(options.generate ?? (async (request: GenerationRequest) => ({ ok: true as const, disassembly: await generated(request), stats }))),
    cancelGeneration: async () => {},
    generationDraft: vi.fn(async () => options.draft?.() ?? { draft: null }),
    suggest: vi.fn(options.suggest ?? (async (request: SuggestionRequest) => ({ ok: true as const, suggestions: suggestionsFor(request) }))),
    cancelSuggestions: vi.fn(async () => {}),
    onGenerationProgress: listener => { listeners.push(listener); return () => {}; },
    onIncomingSource: listener => { arrivals.push(listener); return () => { arrivals.splice(arrivals.indexOf(listener), 1); }; },
    listLessons: async () => ({ lessons: [], skipped: 0 }),
    listDisassemblies: async () => ({ disassemblies: [], skipped: 0 }),
    openUsageSettings: vi.fn(async () => {}),
    getSettings: async () => settings,
    saveSettings: vi.fn(async next => (settings = next)),
    discoverLocal: vi.fn(async () => options.servers ?? []),
    connectLocal: vi.fn(async address => address.includes('8092') ? { ok: true as const, server: { runtime: 'llamacpp' as const, baseUrl: 'http://127.0.0.1:8092', models: ['qwen3.6-35b-a3b.gguf'] } } : { ok: false as const, failure: failure('local-address') }),
    checkLocalFormat: vi.fn(async model => ({ ok: true as const, check: { enforced: model.runtime !== 'ollama', detail: model.runtime === 'ollama' ? 'Il server ha ignorato lo schema di prova.' : 'Il server ha rispettato lo schema di prova.', checkedAt: '2026-10-22T10:00:00.000Z' } })),
  };
  const bridge: DesktopBridge = {
    getRuntime: async () => ({ platform: 'darwin', mode: 'desktop' }),
    loadProgress: async k => ({ state: saved.get(key(k)) ?? null }),
    saveProgress: async s => { saved.set(key(s), structuredClone(s) as LearnerState); },
    studio,
  };
  return { bridge, studio, emit: (progress: GenerationProgress) => listeners.forEach(l => l(progress)), hand: (incoming: IncomingSource) => arrivals.forEach(l => l(incoming)) };
}
